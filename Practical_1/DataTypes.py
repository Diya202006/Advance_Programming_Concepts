# Print all the Data Types

# Integer
a= 10
print("Integer: ", a)
print("Type: ", type(a))

# Float
b=10.5
print("\n Float: ", b)
print("Type: ", type(b))

# Complex
c= 2 + 3j
print("\n Complex: ", c)
print("Type: ", type(c))

# String
d= "Hello Python"
print("\n String: ", d)
print("Type: ", type(d))

# Boolean
e= True
print("\n Boolean: ", e)
print("Type: ", type(e))

# List
f = [10,20,30, "Python"]
print("\n List: ", f)
print("Type: ", type(f))

#  Tuple
g= (1, 2, 3, "Programming")
print("\n Tuple: ", g)
print("Type: ", type(g))

# set
h= {10,20,30,40,50}
print("\n Set: ", h)
print("Type: ", type(h))
